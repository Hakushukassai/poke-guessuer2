function baseKey(id) {
  return id
    .replace(
      /(megax|megay|mega|alola|galar|hisui|origin|therian|black|white|dawnwings|duskmane|ultra|crowned|ice|shadow|complete|10|primal|resolute|pirouette|unbound|sky|blade|busted)$/i,
      '',
    )
    .replace(/(rotom)(wash|heat|frost|fan|mow)$/i, '$1')
}

function writePack(filename, list) {
  const out = path.join(root, 'src/data', filename)
  fs.writeFileSync(out, JSON.stringify(list, null, 2) + '\n')
  console.log(filename, list.length)
}

const legendary = national.filter((p) => LEGENDARY_BASE.has(baseKey(p.id)))
const starters = national.filter((p) => STARTER_FINALS.has(p.id))
const spooky = national.filter(
  (p) => p.types.includes('あく') || p.types.includes('ゴースト'),
)

writePack('pokemon-legendary.json', legendary)
writePack('pokemon-starters.json', starters)
writePack('pokemon-spooky.json', spooky)
